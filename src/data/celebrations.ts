/**
 * Computes the number of days from referenceDate (defaults to Oct 30, 2026) until the celebration's next occurrence.
 */
export function getDaysUntilCelebration(event: CelebrationEvent, refMonth = 10, refDay = 30): number {
  const daysInMonths = [0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
  const toDayOfYear = (m: number, d: number) => {
    let total = d;
    for (let i = 1; i < m; i++) total += daysInMonths[i];
    return total;
  };
  const currentDOY = toDayOfYear(refMonth, refDay);
  const targetDOY = toDayOfYear(event.month, event.day);
  const diff = targetDOY - currentDOY;
  return diff >= 0 ? diff : 365 + diff;
}

export function getSortedUpcomingCelebrations(refMonth = 10, refDay = 30): (CelebrationEvent & { daysUntil: number })[] {
  return CELEBRATION_EVENTS.map((ev) => ({
    ...ev,
    daysUntil: getDaysUntilCelebration(ev, refMonth, refDay),
  })).sort((a, b) => a.daysUntil - b.daysUntil);
}
